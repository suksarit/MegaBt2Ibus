// =====================================================
// RelayManager.h
// TN Mower Auxiliary Relay Interface
//
// หน้าที่:
// - ควบคุม relay อุปกรณ์เสริม
// - ควบคุมไฟส่องสว่าง
// - ตอบสนองต่อ SystemState
//
// ทำงานร่วมกับ:
// - IBusManager
// - SystemState
//
// IMPORTANT:
// - ไฟล์นี้เป็น interface เท่านั้น
// - ไม่ตัดสิน FAILSAFE ที่นี่
// - Configuration อยู่ใน Config.h
// =====================================================

#pragma once

#include <stdint.h>

#include "Config.h"

// =====================================================
// Relay Manager Class
// =====================================================
//
// การเรียกใช้งาน:
//
// begin()
//   - เรียกครั้งเดียวใน setup()
//
// update()
//   - เรียกเฉพาะ STATE_ACTIVE
//
// safe()
//   - เรียกเมื่อ STATE_DISARMED
//
// failsafe()
//   - เรียกเมื่อ STATE_FAILSAFE
// =====================================================
class RelayManager {
public:

  // ---------------------------------------------------
  // Initialize Relay System
  // ---------------------------------------------------
  //
  // หน้าที่:
  // - setup relay pin
  // - reset runtime state
  // - force relay OFF
  //
  // IMPORTANT:
  // - ต้องเรียกก่อนใช้งานเสมอ
  // ---------------------------------------------------
  static void begin();

  // ---------------------------------------------------
  // Update Relay State
  // ---------------------------------------------------
  //
  // หน้าที่:
  // - อ่านคำสั่งจาก IBusManager
  // - update relay output
  // - ลด relay chatter
  //
  // IMPORTANT:
  // - non-blocking only
  // - ใช้เฉพาะ STATE_ACTIVE
  // ---------------------------------------------------
  static void update();

  // ---------------------------------------------------
  // Safe State
  // ---------------------------------------------------
  //
  // หน้าที่:
  // - ปิด relay ทั้งหมด
  //
  // ใช้เมื่อ:
  // - STATE_DISARMED
  // ---------------------------------------------------
  static void safe();

  // ---------------------------------------------------
  // FAILSAFE State
  // ---------------------------------------------------
  //
  // หน้าที่:
  // - force relay OFF
  // - reset runtime state
  //
  // IMPORTANT:
  // - safety priority สูงสุด
  // ---------------------------------------------------
  static void failsafe();
};

