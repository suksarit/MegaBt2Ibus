// =====================================================
// SystemState.h
// Global System State Definition
//
// หน้าที่ของไฟล์นี้:
// - ประกาศ "สถานะกลาง" ของระบบทั้งหมด
// - ใช้เป็นจุดอ้างอิงเดียว (Single Source of Truth)
// - ห้ามใส่ logic การตัดสินใจในไฟล์นี้
//
// Logic การเปลี่ยน state ต้องอยู่ใน SystemState.cpp เท่านั้น
// =====================================================

#pragma once

// -----------------------------------------------------
// System State Enumeration
// -----------------------------------------------------
// STATE_DISARMED
//   - ระบบยังไม่ถูก ARM
//   - ห้ามขับเคลื่อน
//   - เครื่องยนต์ต้องดับ
//   - รีเลย์ทั้งหมด OFF
//
// STATE_ACTIVE
//   - ระบบถูก ARM และไม่อยู่ใน FAILSAFE
//   - อนุญาตให้ขับเคลื่อนและควบคุมเครื่องยนต์
//
// STATE_FAILSAFE
//   - เกิดความผิดปกติ (เช่น IBUS หาย)
//   - ต้องตัดการทำงานทุกอย่างทันที
// -----------------------------------------------------
enum SystemState_t : uint8_t {
  STATE_DISARMED = 0,
  STATE_ACTIVE   = 1,
  STATE_FAILSAFE = 2
};

// -----------------------------------------------------
// SystemState Class Interface
// -----------------------------------------------------
// หมายเหตุ:
// - ทุกฟังก์ชันเป็น static เพื่อให้เรียกใช้ได้จากทุกโมดูล
// - ไม่อนุญาตให้ module อื่น "เดา state เอง"
// - ต้องเรียกผ่าน SystemState เท่านั้น
// -----------------------------------------------------
class SystemState {
public:

  // ตั้งค่า state โดยตรง (ใช้เฉพาะตอน init หรือ override ฉุกเฉิน)
  static void set(SystemState_t s);

  // อ่าน state ปัจจุบัน
  static SystemState_t get();

  // อัปเดต state ตามข้อมูลจาก SafetyManager
  // (เช่น ARM, FAILSAFE)
  static void update();
};
